// Package testpkg makes small packages of each format in Go, for tests:
// the layout each format's own tool writes, with one file installed.
package testpkg

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"fmt"
	"slices"
	"strings"
	"time"

	"github.com/klauspost/compress/zstd"
)

var epoch = time.Unix(1_700_000_000, 0).UTC()

type entry struct {
	name string
	body string
	dir  bool
}

func tarOf(entries []entry, end bool) []byte {
	var b bytes.Buffer

	tw := tar.NewWriter(&b)

	for _, e := range entries {
		h := &tar.Header{Name: e.name, Mode: 0o644, Size: int64(len(e.body)), ModTime: epoch, Typeflag: tar.TypeReg, Format: tar.FormatUSTAR}
		if e.dir {
			h.Mode, h.Size, h.Typeflag = 0o755, 0, tar.TypeDir
		}

		if err := tw.WriteHeader(h); err != nil {
			panic(err)
		}

		if _, err := tw.Write([]byte(e.body)); err != nil {
			panic(err)
		}
	}

	if end {
		if err := tw.Close(); err != nil {
			panic(err)
		}
	} else if err := tw.Flush(); err != nil {
		panic(err)
	}

	return b.Bytes()
}

func gz(b []byte) []byte {
	var out bytes.Buffer

	w := gzip.NewWriter(&out)
	_, _ = w.Write(b) //nolint:errcheck // a buffer
	_ = w.Close()     //nolint:errcheck // a buffer

	return out.Bytes()
}

// Deb is a Debian package installing /usr/share/<name>/who.
func Deb(name, version, arch string) []byte {
	control := fmt.Sprintf("Package: %s\nVersion: %s\nArchitecture: %s\nMaintainer: piperepo <piperepo@localhost>\nInstalled-Size: 1\nDepends: libc6 (>= 2.36), zlib1g\nHomepage: https://example.org/%s\nDescription: made by a test\n a longer line\n", name, version, arch, name)
	members := []struct {
		name string
		body []byte
	}{
		{"debian-binary", []byte("2.0\n")},
		{"control.tar.gz", gz(tarOf([]entry{{name: "./", dir: true}, {name: "./control", body: control}}, true))},
		{"data.tar.gz", gz(tarOf([]entry{
			{name: "./", dir: true}, {name: "./usr/", dir: true}, {name: "./usr/share/", dir: true}, {name: "./usr/share/" + name + "/", dir: true},
			{name: "./usr/share/" + name + "/who", body: "made by " + version + "\n"},
			{name: "./usr/share/doc/", dir: true}, {name: "./usr/share/doc/" + name + "/", dir: true},
			{name: "./usr/share/doc/" + name + "/copyright", body: "Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/\n\nFiles: *\nLicense: MIT\n"},
		}, true))},
	}

	var ar bytes.Buffer

	ar.WriteString("!<arch>\n")

	for _, m := range members {
		fmt.Fprintf(&ar, "%-16s%-12d%-6d%-6d%-8s%-10d`\n", m.name, 0, 0, 0, "100644", len(m.body))
		ar.Write(m.body)

		if len(m.body)%2 == 1 {
			ar.WriteByte('\n')
		}
	}

	return ar.Bytes()
}

// Arch is a pacman package installing /usr/share/<name>/who.
func Arch(name, version, arch string) []byte {
	info := fmt.Sprintf("# Generated by makepkg\npkgname = %s\npkgbase = %s\npkgver = %s\npkgdesc = made by a test\nurl = https://example.org/%s\nbuilddate = %d\npackager = piperepo\nsize = 12\narch = %s\nlicense = MIT\ndepend = glibc\n", name, name, version, name, epoch.Unix(), arch)
	t := tarOf([]entry{
		{name: ".PKGINFO", body: info}, {name: ".MTREE", body: "x"},
		{name: "usr/", dir: true}, {name: "usr/share/", dir: true}, {name: "usr/share/" + name + "/", dir: true},
		{name: "usr/share/" + name + "/who", body: "made by " + version + "\n"},
	}, true)

	var b bytes.Buffer

	w, err := zstd.NewWriter(&b)
	if err != nil {
		panic(err)
	}

	_, _ = w.Write(t) //nolint:errcheck // a buffer
	_ = w.Close()     //nolint:errcheck // a buffer

	return b.Bytes()
}

// APK is an Alpine v2 package, unsigned: its control and data segments.
func APK(name, version, arch string) []byte {
	data := tarOf([]entry{
		{name: "usr/", dir: true}, {name: "usr/share/", dir: true}, {name: "usr/share/" + name + "/", dir: true},
		{name: "usr/share/" + name + "/who", body: "made by " + version + "\n"},
	}, true)
	sum := sha256.Sum256(gz(data))
	info := fmt.Sprintf("# Generated by abuild\npkgname = %s\npkgver = %s\npkgdesc = made by a test\nurl = https://example.org/%s\nbuilddate = %d\npackager = piperepo\nsize = 12\narch = %s\norigin = %s\nlicense = MIT\ndepend = musl\ndatahash = %s\n", name, version, name, epoch.Unix(), arch, name, hex.EncodeToString(sum[:]))

	return append(gz(tarOf([]entry{{name: ".PKGINFO", body: info}}, false)), gz(data)...)
}

// rpmEntry is one header entry being written.
type rpmEntry struct {
	tag   uint32
	typ   uint32
	count uint32
	data  []byte
}

func rpmString(tag uint32, s string) rpmEntry {
	return rpmEntry{tag: tag, typ: 6, count: 1, data: append([]byte(s), 0)}
}

func rpmStrings(tag uint32, ss ...string) rpmEntry {
	var b []byte
	for _, s := range ss {
		b = append(append(b, s...), 0)
	}

	return rpmEntry{tag: tag, typ: 8, count: uint32(len(ss)), data: b} //nolint:gosec // a test's few
}

func rpmInts(tag uint32, ns ...uint32) rpmEntry {
	b := make([]byte, 4*len(ns))
	for i, n := range ns {
		binary.BigEndian.PutUint32(b[i*4:], n)
	}

	return rpmEntry{tag: tag, typ: 4, count: uint32(len(ns)), data: b} //nolint:gosec // a test's few
}

func rpmShorts(tag uint32, ns ...uint16) rpmEntry {
	b := make([]byte, 2*len(ns))
	for i, n := range ns {
		binary.BigEndian.PutUint16(b[i*2:], n)
	}

	return rpmEntry{tag: tag, typ: 3, count: uint32(len(ns)), data: b} //nolint:gosec // a test's few
}

func rpmHeader(entries []rpmEntry) []byte {
	slices.SortFunc(entries, func(a, b rpmEntry) int { return int(a.tag) - int(b.tag) })

	var index, store bytes.Buffer

	for _, e := range entries {
		align := map[uint32]int{3: 2, 4: 4, 5: 8}[e.typ]
		for align > 0 && store.Len()%align != 0 {
			store.WriteByte(0)
		}

		var ix [16]byte
		binary.BigEndian.PutUint32(ix[0:], e.tag)
		binary.BigEndian.PutUint32(ix[4:], e.typ)
		binary.BigEndian.PutUint32(ix[8:], uint32(store.Len())) //nolint:gosec // small
		binary.BigEndian.PutUint32(ix[12:], e.count)
		index.Write(ix[:])
		store.Write(e.data)
	}

	var h bytes.Buffer

	h.Write([]byte{0x8e, 0xad, 0xe8, 0x01, 0, 0, 0, 0})
	_ = binary.Write(&h, binary.BigEndian, uint32(len(entries))) //nolint:errcheck,gosec // a buffer; small
	_ = binary.Write(&h, binary.BigEndian, uint32(store.Len()))  //nolint:errcheck,gosec // a buffer; small
	h.Write(index.Bytes())
	h.Write(store.Bytes())

	return h.Bytes()
}

// RPM is an rpm package's lead and headers, with an empty payload: what
// repodata reads. dnf can't install it; the real client tests build theirs
// with rpmbuild.
func RPM(name, version, release, arch string) []byte {
	lead := make([]byte, 96)
	copy(lead, []byte{0xed, 0xab, 0xee, 0xdb, 3, 0})
	copy(lead[10:], name+"-"+version+"-"+release)
	binary.BigEndian.PutUint16(lead[78:], 5)

	sig := rpmHeader([]rpmEntry{rpmInts(1000, 1234), rpmInts(1007, 0)})
	for len(sig)%8 != 0 {
		sig = append(sig, 0)
	}

	h := rpmHeader([]rpmEntry{
		rpmString(1000, name), rpmString(1001, version), rpmString(1002, release),
		{tag: 1004, typ: 9, count: 1, data: []byte("made by a test\x00")},
		{tag: 1005, typ: 9, count: 1, data: []byte("A package made by a test.\x00")},
		rpmInts(1006, uint32(epoch.Unix())), rpmString(1007, "localhost"), rpmInts(1009, 12), //nolint:gosec // a fixed time
		rpmString(1014, "MIT"), rpmString(1020, "https://example.org/"+name), rpmString(1022, arch),
		rpmInts(1028, 0, 0, 12), rpmShorts(1030, 0o40755, 0o40755, 0o100644), rpmString(1044, name+"-"+version+"-"+release+".src.rpm"),
		rpmStrings(1047, name), rpmInts(1112, 8), rpmStrings(1113, version+"-"+release),
		rpmStrings(1049, "/bin/sh", "rpmlib(CompressedFileNames)", "glibc"), rpmInts(1048, 0, 1<<24|12, 12), rpmStrings(1050, "", "3.0.4-1", "2.36"),
		rpmInts(1116, 0, 1, 2), rpmStrings(1117, "share", name, "who"), rpmStrings(1118, "/usr/", "/usr/share/", "/usr/share/"+name+"/"),
	})

	return slices.Concat(lead, sig, h, gz(nil))
}

// Name is a package file's usual name in its format.
func Name(format, name, version, arch string) string {
	switch format {
	case "apt":
		return name + "_" + version + "_" + arch + ".deb"
	case "arch":
		return name + "-" + version + "-" + arch + ".pkg.tar.zst"
	case "apk":
		return name + "-" + version + ".apk"
	default:
		return name + "-" + version + "." + arch + ".rpm"
	}
}

// Of is a package of a format.
func Of(format, name, version, arch string) []byte {
	switch format {
	case "apt":
		return Deb(name, version, arch)
	case "arch":
		return Arch(name, version, arch)
	case "apk":
		return APK(name, version, arch)
	default:
		v, r, _ := strings.Cut(version, "-")
		if r == "" {
			r = "1"
		}

		return RPM(name, v, r, arch)
	}
}
